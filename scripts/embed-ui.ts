// Embed the built UI into the app so the compiled binary needs no files next to it.
import { Glob } from "bun";
const dist = new URL("../packages/ui/dist/", import.meta.url).pathname;
const out: Record<string, { type: string; b64: string }> = {};
for await (const f of new Glob("**/*").scan(dist)) {
  const file = Bun.file(dist + f);
  out["/" + f] = { type: file.type, b64: Buffer.from(await file.arrayBuffer()).toString("base64") };
}
await Bun.write(new URL("../apps/app/src/ui-assets.ts", import.meta.url).pathname,
  `// Generated by scripts/embed-ui.ts — do not edit.\nexport const assets: Record<string, { type: string; b64: string }> = ${JSON.stringify(out)};\n`);
console.log(`embedded ${Object.keys(out).length} UI files`);
