// Embed the local microVM engine (smolmachines SDK + this target's native package) into the app, so the
// compiled binary runs agents in a microVM with nothing else installed. Usage: bun scripts/embed-engine.ts <bun-target>
// Writes packages/drivers/src/engine-blob.ts (not in git) pointing at dist/engine/<target>.bin, which
// `bun build --compile` embeds. Targets without an engine (Windows, Intel Macs) get `engine = null`.
import { Glob } from "bun";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const target = (process.argv[2] ?? "").replace(/^bun-/, "");
const PKG: Record<string, string> = {
  "darwin-arm64": "smolmachines-darwin-arm64",
  "linux-x64": "smolmachines-linux-x64-gnu",
  "linux-arm64": "smolmachines-linux-arm64-gnu",
};
const out = join(root, "packages/drivers/src/engine-blob.ts");
const pkg = PKG[target];
if (!pkg) {
  await Bun.write(out, `// Generated by scripts/embed-engine.ts — do not edit.\nexport const engine: { version: string; platform: string; blob: string } | null = null;\n`);
  console.log(`no local engine for ${target}`);
  process.exit(0);
}

const lock = readFileSync(join(root, "bun.lock"), "utf8");
function locked(name: string): { version: string; integrity: string } {
  const m = lock.match(new RegExp(`"${name}": \\["${name}@([^"]+)",[^\\n]*"(sha512-[^"]+)"\\]`));
  if (!m) throw new Error(`${name} is not in bun.lock`);
  return { version: m[1]!, integrity: m[2]! };
}

/** The installed package dir, or the registry tarball (checked against bun.lock) unpacked into dist/engine/. */
async function packageDir(name: string): Promise<string> {
  const { version, integrity } = locked(name);
  const installed = join(root, `node_modules/.bun/${name}@${version}/node_modules/${name}`);
  if (existsSync(join(installed, "package.json"))) return installed;
  const dir = join(root, `dist/engine/${name}-${version}`);
  if (existsSync(join(dir, "package/package.json"))) return join(dir, "package");
  mkdirSync(dir, { recursive: true });
  const url = `https://registry.npmjs.org/${name}/-/${name}-${version}.tgz`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const tgz = new Uint8Array(await res.arrayBuffer());
  const got = "sha512-" + createHash("sha512").update(tgz).digest("base64");
  if (got !== integrity) throw new Error(`${name}@${version}: checksum mismatch (bun.lock ${integrity}, got ${got})`);
  await Bun.write(join(dir, "pkg.tgz"), tgz);
  const x = Bun.spawnSync(["tar", "-xzf", join(dir, "pkg.tgz"), "-C", dir]);
  if (x.exitCode !== 0) throw new Error(`unpacking ${name}: ${x.stderr.toString()}`);
  return join(dir, "package");
}

const sdk = await packageDir("smolmachines");
const native = await packageDir(pkg);
// Laid out the way the SDK finds its assets in a source checkout (the addon next to dist/binding.js, the boot
// helper, libraries and rootfs in native/<platform>/), so loading needs no package lookup by name, which a
// compiled Bun binary can't do from disk.
const files: { path: string; mode: number; data: Uint8Array }[] = [];
async function add(from: string, place: (f: string) => string | undefined) {
  for await (const f of new Glob("**/*").scan({ cwd: from, onlyFiles: true })) {
    const to = place(f);
    if (!to) continue;
    const p = join(from, f);
    files.push({ path: `smolmachines/${to}`, mode: statSync(p).mode & 0o777, data: new Uint8Array(readFileSync(p)) });
  }
}
await add(sdk, (f) => (f === "package.json" || f.startsWith("dist/") ? f : undefined));
await add(native, (f) => (f.endsWith(".node") && !f.includes("/") ? `dist/${f}` : f.startsWith("native/") ? `native/${target}/${f.slice(7)}` : undefined));

// Archive: 4-byte header length, JSON header, then the files back to back; zstd-compressed as a whole.
const header = new TextEncoder().encode(JSON.stringify(files.map(({ path, mode, data }) => ({ path, mode, size: data.length }))));
const len = new Uint8Array(4);
new DataView(len.buffer).setUint32(0, header.length);
const raw = Buffer.concat([len, header, ...files.map((f) => f.data)]);
const blob = Bun.zstdCompressSync(raw, { level: 19 });
const version = `${locked("smolmachines").version}-${createHash("sha256").update(raw).digest("hex").slice(0, 12)}`;
const binPath = join(root, `dist/engine/${target}.bin`);
mkdirSync(dirname(binPath), { recursive: true });
await Bun.write(binPath, blob);
await Bun.write(out, `// Generated by scripts/embed-engine.ts — do not edit.
import blob from "../../../dist/engine/${target}.bin" with { type: "file" };
export const engine: { version: string; platform: string; blob: string } | null = { version: ${JSON.stringify(version)}, platform: ${JSON.stringify(target)}, blob };
`);
console.log(`embedded smolmachines ${version} for ${target}: ${files.length} files, ${(raw.length / 1e6).toFixed(0)} MB → ${(blob.length / 1e6).toFixed(0)} MB`);
