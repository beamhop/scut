// Embed the agent's own code (see apps/app/src/agent-code.ts) into the app, so agents run the app's exact version.
import { buildAgentCode } from "../apps/app/src/agent-code.ts";
const c = await buildAgentCode();
const files = Object.fromEntries(Object.entries(c.files).map(([k, v]) => [k, Buffer.from(v).toString("base64")]));
await Bun.write(new URL("../apps/app/src/agent-code.gen.ts", import.meta.url).pathname,
  `// Generated by scripts/embed-agent-code.ts — do not edit.\nexport const code = ${JSON.stringify({ hash: c.hash, files })};\n`);
console.log(`embedded the agent's code ${c.hash} (${Object.keys(files).length} files)`);
